// Generates src/lib/database.types.ts (supabase-js "Database" type) by applying
// the migrations to an embedded Postgres and introspecting the public schema.
// Usage: npm run db:types
import { writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { startDatabase } from "../tests/db/harness.mjs";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");

const TYPE_MAP = {
  uuid: "string", text: "string", varchar: "string", bpchar: "string", citext: "string",
  int2: "number", int4: "number", int8: "number", float4: "number", float8: "number", numeric: "number",
  bool: "boolean",
  timestamptz: "string", timestamp: "string", date: "string", time: "string", timetz: "string", interval: "string",
  json: "Json", jsonb: "Json",
  void: "undefined", record: "Json",
};

function tsType(udt) {
  if (udt.startsWith("_")) return `${tsType(udt.slice(1))}[]`;
  return TYPE_MAP[udt] ?? "unknown";
}

const db = await startDatabase();
const { client } = db;
try {
  const { rows: columns } = await client.query(`
    select c.table_name, c.column_name, c.udt_name, c.is_nullable = 'YES' as nullable,
           (c.column_default is not null or c.is_identity = 'YES') as has_default
    from information_schema.columns c
    join information_schema.tables t on t.table_schema = c.table_schema and t.table_name = c.table_name
    where c.table_schema = 'public' and t.table_type = 'BASE TABLE'
    order by c.table_name, c.ordinal_position`);

  const { rows: fks } = await client.query(`
    select con.conname, src.relname as table_name, tgt.relname as referenced_table,
           array(select a.attname from unnest(con.conkey) with ordinality k(attnum, ord)
                 join pg_attribute a on a.attrelid = con.conrelid and a.attnum = k.attnum order by k.ord)::text[] as columns,
           array(select a.attname from unnest(con.confkey) with ordinality k(attnum, ord)
                 join pg_attribute a on a.attrelid = con.confrelid and a.attnum = k.attnum order by k.ord)::text[] as referenced_columns,
           exists (
             select 1 from pg_constraint u
             where u.conrelid = con.conrelid and u.contype in ('p', 'u')
               and (select array_agg(x order by x) from unnest(u.conkey) x) = (select array_agg(x order by x) from unnest(con.conkey) x)
           ) as one_to_one
    from pg_constraint con
    join pg_class src on src.oid = con.conrelid
    join pg_namespace sn on sn.oid = src.relnamespace
    join pg_class tgt on tgt.oid = con.confrelid
    join pg_namespace tn on tn.oid = tgt.relnamespace
    where con.contype = 'f' and sn.nspname = 'public' and tn.nspname = 'public'
    order by con.conname`);

  const { rows: functions } = await client.query(`
    select p.proname, p.proretset, rt.typname as return_type, p.pronargdefaults,
           coalesce(p.proargnames, '{}') as arg_names,
           coalesce(p.proargmodes::text[], '{}') as arg_modes,
           array(select t.typname from unnest(coalesce(p.proallargtypes, p.proargtypes::oid[])) with ordinality a(oid, ord)
                 join pg_type t on t.oid = a.oid order by a.ord)::text[] as arg_types
    from pg_proc p
    join pg_namespace n on n.oid = p.pronamespace
    join pg_type rt on rt.oid = p.prorettype
    where n.nspname = 'public' and rt.typname <> 'trigger' and p.prokind = 'f'
      and not exists (select 1 from pg_depend d where d.objid = p.oid and d.deptype = 'e')
    order by p.proname`);

  const tables = new Map();
  for (const col of columns) {
    if (!tables.has(col.table_name)) tables.set(col.table_name, []);
    tables.get(col.table_name).push(col);
  }

  const out = [];
  out.push("// Generated by scripts/generate-db-types.mjs – do not edit by hand.");
  out.push("// Run `npm run db:types` after changing a migration.");
  out.push("");
  out.push("export type Json = string | number | boolean | null | { [key: string]: Json | undefined } | Json[];");
  out.push("");
  out.push("export type Database = {");
  out.push('  __InternalSupabase: { PostgrestVersion: "13" };');
  out.push("  public: {");
  out.push("    Tables: {");
  for (const [table, cols] of tables) {
    out.push(`      ${table}: {`);
    out.push("        Row: {");
    for (const c of cols) out.push(`          ${c.column_name}: ${tsType(c.udt_name)}${c.nullable ? " | null" : ""};`);
    out.push("        };");
    out.push("        Insert: {");
    for (const c of cols) {
      const optional = c.nullable || c.has_default;
      out.push(`          ${c.column_name}${optional ? "?" : ""}: ${tsType(c.udt_name)}${c.nullable ? " | null" : ""};`);
    }
    out.push("        };");
    out.push("        Update: {");
    for (const c of cols) out.push(`          ${c.column_name}?: ${tsType(c.udt_name)}${c.nullable ? " | null" : ""};`);
    out.push("        };");
    const rels = fks.filter((f) => f.table_name === table);
    if (rels.length === 0) {
      out.push("        Relationships: [];");
    } else {
      out.push("        Relationships: [");
      for (const r of rels) {
        out.push("          {");
        out.push(`            foreignKeyName: ${JSON.stringify(r.conname)};`);
        out.push(`            columns: ${JSON.stringify(r.columns)};`);
        out.push(`            isOneToOne: ${r.one_to_one};`);
        out.push(`            referencedRelation: ${JSON.stringify(r.referenced_table)};`);
        out.push(`            referencedColumns: ${JSON.stringify(r.referenced_columns)};`);
        out.push("          },");
      }
      out.push("        ];");
    }
    out.push("      };");
  }
  out.push("    };");
  out.push("    Views: { [_ in never]: never };");
  out.push("    Functions: {");
  for (const fn of functions) {
    const names = fn.arg_names;
    const modes = fn.arg_modes.length ? fn.arg_modes : names.map(() => "i");
    const inputs = [];
    const outputs = [];
    names.forEach((name, i) => {
      const entry = { name, type: tsType(fn.arg_types[i]) };
      if (modes[i] === "t" || modes[i] === "o") outputs.push(entry);
      else inputs.push(entry);
    });
    const firstDefault = inputs.length - fn.pronargdefaults;
    const args = inputs.length
      ? `{ ${inputs.map((a, i) => `${a.name}${i >= firstDefault ? "?" : ""}: ${a.type}`).join("; ")} }`
      : "never";
    let returns;
    if (outputs.length) {
      returns = `{ ${outputs.map((o) => `${o.name}: ${o.type} | null`).join("; ")} }[]`;
    } else {
      returns = tsType(fn.return_type) + (fn.proretset ? "[]" : "");
    }
    out.push(`      ${fn.proname}: { Args: ${args}; Returns: ${returns} };`);
  }
  out.push("    };");
  out.push("    Enums: { [_ in never]: never };");
  out.push("    CompositeTypes: { [_ in never]: never };");
  out.push("  };");
  out.push("};");
  out.push("");
  out.push('type PublicSchema = Database["public"];');
  out.push('export type Tables<T extends keyof PublicSchema["Tables"]> = PublicSchema["Tables"][T]["Row"];');
  out.push('export type TablesInsert<T extends keyof PublicSchema["Tables"]> = PublicSchema["Tables"][T]["Insert"];');
  out.push('export type TablesUpdate<T extends keyof PublicSchema["Tables"]> = PublicSchema["Tables"][T]["Update"];');
  out.push("");

  writeFileSync(join(root, "src/lib/database.types.ts"), out.join("\n"));
  console.log(`Wrote src/lib/database.types.ts (${tables.size} tables, ${functions.length} functions)`);
} finally {
  await db.stop();
}
